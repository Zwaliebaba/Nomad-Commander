// The font, and the whole of it: 96 glyphs, ASCII 0x20 to 0x7F, eight bytes a glyph, one bit a pixel, most
// significant bit leftmost. 768 bytes, compiled into the executable, with nothing to load (AGENTS.md R13).
//
// **Provenance: authored for this repository.** It is not derived from any published font, so there is no licence to
// honour and no attribution owed (R14's spirit: the closed dependency list covers art as well as code). The shapes
// were designed as pictures and the bytes derived from them, which is why they are written in binary below -- a
// reader can see the letter, and an editor can change it by moving a 1.
//
// Six columns wide of the eight, so a character carries its own spacing; rows 0 to 6 for capitals and row 7 for the
// line below, which is where the descenders of g, j, p, q and y reach. 0x7F is a filled box, drawn for any character
// this font does not have, so a missing glyph is loud rather than invisible.
